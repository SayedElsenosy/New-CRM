/**
 * Safe retrieval of synthetic domain examples. Topic is authoritative for
 * general guidance only, not for salary, geography, hiring or eligibility.
 */
export function matchExpertTopic(text){
 const raw=String(text||'').trim();
 if(raw.length<5||raw.length>500||PII_PATTERN.test(raw))return null;
 if(!questionCue.test(raw)&&!looksLikeQuestion(raw))return null;
 const q=normalize(raw),hit=exact.get(q);
 if(hit)return {topic:byId.get(hit),confidence:1,match:'curated_example'};
 let best=null;
 const qWords=new Set(words(q));
 for(const topic of EXPERT_TOPICS){
  const signal=topic.signal?.test(q);
  let lexical=0;
  for(const example of topic.examples){
   const eWords=new Set(words(example));if(!eWords.size||!qWords.size)continue;
   const overlap=[...qWords].filter(x=>eWords.has(x)).length;
   const candidate=overlap/Math.max(qWords.size,eWords.size);
   lexical=Math.max(lexical,candidate);
  }
  const score=signal?Math.max(.84,Math.min(.97,lexical*.90+.16)):lexical>=.78?Math.min(.88,lexical*.9):0;
  if(score>.77&&(!best||score>best.confidence))best={topic,confidence:score,match:signal?'topic_signal':'example_similarity'};
 }
 return best;
}

/**
 * Prefers office-confirmed knowledge. General expert text is a fallback only;
 * it cannot import a policy, salary or employment condition into the CRM.
 */
export function expertResponse(text,{knowledge=[],knowledgeEnabled=true,minConfidence=.76}={}){
 const matched=matchExpertTopic(text);
 if(!matched)return null;
 const trusted=knowledgeEnabled?findKnowledgeAnswer(text,knowledge,Math.max(.72,Number(minConfidence)||.76)) :null;
 if(trusted){
  return {intent:matched.topic.id,reply:String(trusted.answer||'').trim(),origin:'office_verified',knowledge_id:trusted.id,
   confidence:trusted.confidence,training_version:'expert-v1'};
 }
 return {intent:matched.topic.id,reply:matched.topic.reply,origin:'general_guidance',knowledge_id:null,
  confidence:matched.confidence,training_version:'expert-v1'};
}

